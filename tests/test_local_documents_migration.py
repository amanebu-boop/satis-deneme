from pathlib import Path

from app import storage
from scripts.migrate_local_documents_to_s3 import migrate_documents


def test_document_migration_is_dry_run_first_and_checksum_verified(tmp_path: Path, monkeypatch):
    (tmp_path / "0123456789abcdef0123456789abcdef.source").write_bytes(b"template bytes")
    (tmp_path / "0123456789abcdef0123456789abcdef.json").write_text('{"id":"0123456789abcdef0123456789abcdef"}', encoding="utf-8")
    (tmp_path / "abcdef0123456789abcdef0123456789.output.xlsx").write_bytes(b"generated bytes")

    objects = {}
    monkeypatch.setattr(storage, "is_s3", lambda: True)
    monkeypatch.setattr(storage, "exists", lambda key: key in objects)
    monkeypatch.setattr(storage, "get_bytes", lambda key: objects[key])
    monkeypatch.setattr(storage, "put_bytes", lambda key, data, content_type="application/octet-stream": objects.__setitem__(key, data))

    preview = migrate_documents(tmp_path, apply=False)
    assert preview["files"] == 3
    assert preview["mode"] == "dry-run"
    assert objects == {}

    applied = migrate_documents(tmp_path, apply=True)
    assert applied["mode"] == "apply"
    assert len(objects) == 3
    assert objects["templates/0123456789abcdef0123456789abcdef.source"] == b"template bytes"
    assert objects["outputs/abcdef0123456789abcdef0123456789.output.xlsx"] == b"generated bytes"

    repeated = migrate_documents(tmp_path, apply=True)
    assert all(item["action"] == "already-matches" for item in repeated["objects"])
